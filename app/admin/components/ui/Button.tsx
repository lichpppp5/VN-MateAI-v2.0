'use client';

import * as React from 'react';
import { Slot } from '@radix-ui/react-slot';
import { cva, type VariantProps } from 'class-variance-authority';
import { cn } from '@/lib/utils';

const buttonVariants = cva(
  'inline-flex items-center justify-center whitespace-nowrap rounded-lg text-sm font-medium ring-offset-background transition-all duration-200 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 active:scale-[0.98]',
  {
    variants: {
      variant: {
        default: 'bg-vnmate-cyan/10 text-vnmate-cyan border border-vnmate-cyan/30 hover:bg-vnmate-cyan/20 hover:shadow-glow-cyan',
        destructive: 'bg-vnmate-pink/10 text-vnmate-pink border border-vnmate-pink/30 hover:bg-vnmate-pink/20 hover:shadow-[0_0_20px_rgba(236,72,153,0.3)]',
        outline: 'border border-vnmate-slate-700 bg-vnmate-slate-900/50 hover:bg-vnmate-slate-800/50 hover:border-vnmate-cyan/50',
        secondary: 'bg-vnmate-slate-800 text-vnmate-neon border border-vnmate-slate-700 hover:bg-vnmate-slate-700',
        ghost: 'hover:bg-vnmate-slate-800/50 hover:text-vnmate-cyan',
        link: 'text-vnmate-cyan underline-offset-4 hover:underline',
        cyber: 'btn-cyber',
        'cyber-emerald': 'btn-cyber-emerald',
        'cyber-destructive': 'btn-cyber-destructive',
      },
      size: {
        default: 'h-10 px-4 py-2',
        sm: 'h-9 rounded-md px-3',
        lg: 'h-11 rounded-lg px-8',
        xl: 'h-12 rounded-lg px-10 text-base',
        icon: 'h-10 w-10',
      },
    },
    defaultVariants: {
      variant: 'default',
      size: 'default',
    },
  }
);

export interface ButtonProps
  extends React.ButtonHTMLAttributes<HTMLButtonElement>,
    VariantProps<typeof buttonVariants> {
  asChild?: boolean;
  loading?: boolean;
}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant, size, asChild = false, loading, children, disabled, ...props }, ref) => {
    const Comp = asChild ? Slot : 'button';
    return (
      <Comp
        className={cn(buttonVariants({ variant, size, className }))}
        ref={ref}
        disabled={disabled || loading}
        {...props}
      >
        {loading ? (
          <>
            <svg
              className="mr-2 h-4 w-4 animate-spin"
              xmlns="http://www.w3.org/2000/svg"
              fill="none"
              viewBox="0 0 24 24"
            >
              <circle
                className="opacity-25"
                cx="12"
                cy="12"
                r="10"
                stroke="currentColor"
                strokeWidth="4"
              />
              <path
                className="opacity-75"
                fill="currentColor"
                d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"
              />
            </svg>
            Loading...
          </>
        ) : (
          children
        )}
      </Comp>
    )
  }
);
Button.displayName = 'Button';

export { Button, buttonVariants };