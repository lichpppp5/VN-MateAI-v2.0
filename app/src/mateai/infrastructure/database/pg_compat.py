"""
mateai/infrastructure/database/pg_compat.py
===========================================
Chạy tầng persistence (viết cho SQLite) trên PostgreSQL — prompt cuối §65 (cutover).

`open_sqlite()` (erp_database) là điểm mở kết nối DUY NHẤT; khi có `DATABASE_URL`
(postgresql://…) nó trả `PgConnection` ở đây — cùng giao diện mà code đang dùng:
`execute / cursor / executemany / executescript / fetch* / lastrowid / rowcount / with`,
dòng kết quả vừa đánh chỉ số vừa đọc theo tên (như `sqlite3.Row`).

Dịch SQL (chỉ những gì repo dùng — kiểm bằng toàn bộ bộ test chạy trên PostgreSQL):
  `?` -> `%s`, `%` -> `%%` · `LIKE` -> `ILIKE` (SQLite không phân biệt hoa thường với ASCII)
  `INSERT OR IGNORE` -> `ON CONFLICT DO NOTHING` · `INSERT OR REPLACE` -> `ON CONFLICT (pk) DO UPDATE`
  `datetime('now', '-N days')` -> `to_char(now() - interval …)`
  DDL: `INTEGER PRIMARY KEY [AUTOINCREMENT]` -> identity; kiểu theo `sqlite_type_to_pg` (dùng chung
  với công cụ di trú); `DEFAULT CURRENT_TIMESTAMP` -> chuỗi cùng định dạng SQLite
  `PRAGMA table_info` -> information_schema · PRAGMA khác -> bỏ qua
  INSERT vào bảng có cột identity -> thêm `RETURNING` để `lastrowid` đúng như SQLite.
Kiểu: bool -> 0/1, datetime -> chuỗi như sqlite3, Decimal trả về -> int / float.
"""
