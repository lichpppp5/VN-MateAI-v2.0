def connect(sqlite_path: Any, timeout: float = 30.0) -> PgConnection:
    from psycopg_pool import ConnectionPool
    url, schema = database_url(), schema_for(sqlite_path)
    key = f"{url}#{schema}"
    with _POOLS_LOCK:
        pool = _POOLS.get(key)
        if pool is None:
            def _configure(conn):
                import psycopg
                try:
                    conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{schema}"')
                    conn.commit()
                except psycopg.errors.UniqueViolation:
                    conn.rollback()      # pool khác vừa tạo cùng lúc (race của CREATE SCHEMA IF NOT EXISTS)
                conn.execute(f'SET search_path TO "{schema}"')
                conn.commit()
            pool = ConnectionPool(url, min_size=1, max_size=10, timeout=timeout, configure=_configure,
                                  kwargs={"connect_timeout": 10}, open=True)
            _POOLS[key] = pool
    raw = pool.getconn(timeout=timeout)

    def _release(c):
        try:
            if c.info.transaction_status != 0:      # còn transaction dở -> huỷ trước khi trả
                c.rollback()
        except Exception:  # noqa: BLE001
            pass
        pool.putconn(c)

    return PgConnection(raw, schema, _release)


def close_pools() -> None:
    with _POOLS_LOCK:
        for p in _POOLS.values():
            try:
                p.close()
            except Exception:  # noqa: BLE001
                pass
        _POOLS.clear()
    clear_catalog_cache()
