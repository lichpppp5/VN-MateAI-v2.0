def database_url() -> str:
    import os
    url = os.environ.get("VNMATEAI_DATABASE_URL", "")
    if url.strip().lower() == "sqlite":          # ép SQLite (bộ test, bản lùi) dù config.json có DATABASE_URL
        return ""
    if not url:
        try:
            from mateai.config.loader import settings
            url = str(getattr(settings, "DATABASE_URL", "") or "")
        except Exception:  # noqa: BLE001
            url = ""
    return url if url.startswith(("postgresql://", "postgres://")) else ""


def schema_for(sqlite_path: Any) -> str:
    """Mỗi FILE SQLite cũ -> một schema PostgreSQL (giữ nguyên tính cô lập "mỗi file một DB"):
    vnmateai.db -> schema chính, hr_kpi.db -> schema nhân sự, đường dẫn khác -> schema riêng theo
    băm đường dẫn (DB tạm của công cụ / test không lẫn vào dữ liệu thật)."""
    import hashlib
